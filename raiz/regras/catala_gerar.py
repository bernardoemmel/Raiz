"""Gera o Python das regras em Catala (E2 passo 2) e confere se o gerado está em dia com as fontes.

`raiz regras gerar` roda o clerk (compilador do Catala, Apache-2.0, instalado pelo opam; só quem edita as regras
precisa dele), copia o módulo e o runtime para raiz/regras/gerado/ e grava ORIGEM.json com o hash de cada fonte.
O teste test_gerado_em_dia falha se alguém mudar um .catala_en sem gerar de novo, então o CI não precisa do opam.

Ajustes no código gerado (mecânicos, sempre os mesmos): os imports absolutos do runtime viram relativos, para o
pacote funcionar dentro de raiz.regras.gerado; os arquivos do stdlib em francês ficam de fora.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

PASTA_CATALA = Path(__file__).with_name("catala")
PASTA_GERADO = Path(__file__).with_name("gerado")
ALVO = "regras_federais"
CABECALHO = "# Gerado por `raiz regras gerar` a partir de raiz/regras/catala/ (Catala, Apache-2.0). Não edite à mão.\n"


def fontes() -> dict[str, str]:
    """sha256 de cada fonte Catala e do clerk.toml, por caminho relativo à pasta das regras."""
    arqs = sorted([*PASTA_CATALA.rglob("*.catala_en"), PASTA_CATALA / "clerk.toml"])
    arqs = [a for a in arqs if "_build" not in a.parts and "_target" not in a.parts]
    return {str(a.relative_to(PASTA_CATALA)): hashlib.sha256(a.read_bytes()).hexdigest() for a in arqs}


def origem_gravada() -> dict:
    f = PASTA_GERADO / "ORIGEM.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}


def em_dia() -> tuple[bool, list[str]]:
    gravada = origem_gravada().get("fontes", {})
    atuais = fontes()
    difs = sorted(k for k in set(gravada) | set(atuais) if gravada.get(k) != atuais.get(k))
    return not difs, difs


def _ambiente_opam() -> dict[str, str]:
    env = dict(os.environ)
    if shutil.which("clerk"):
        return env
    raiz_opam = Path(env.get("OPAMROOT", Path.home() / ".opam"))
    for switch in ("catala", "default"):
        bin_ = raiz_opam / switch / "bin"
        if (bin_ / "clerk").exists():
            env["PATH"] = f"{bin_}{os.pathsep}{env['PATH']}"
            env.setdefault("OPAM_SWITCH_PREFIX", str(raiz_opam / switch))
            return env
    raise FileNotFoundError(
        "clerk (Catala) não encontrado: instale com `opam install catala` (veja raiz/regras/catala/README.md)"
    )


def _rodar(cmd: list[str], env: dict[str, str]) -> str:
    r = subprocess.run(cmd, cwd=PASTA_CATALA, env=env, capture_output=True, text=True, timeout=1800)
    if r.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} falhou:\n{r.stdout[-4000:]}\n{r.stderr[-4000:]}")
    return r.stdout


def _relativo(texto: str) -> str:
    texto = re.sub(r"^from catala_runtime import \*", "from .catala_runtime import *", texto, flags=re.M)
    return re.sub(r"^import dates$", "from . import dates", texto, flags=re.M)


def gerar(testar: bool = True) -> dict:
    env = _ambiente_opam()
    versao = _rodar(["catala", "--version"], env).strip()
    _rodar(["clerk", "start"], env)
    if testar:
        _rodar(["clerk", "test"], env)
    _rodar(["clerk", "build", ALVO], env)
    py = PASTA_CATALA / "_target" / "python"
    tmp = PASTA_GERADO.with_name("gerado.tmp")
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir()
    copiados = []
    origem = [*sorted((py / "libcatala").glob("*.py")), *sorted((py / ALVO).glob("*.py"))]
    for arq in origem:
        if arq.name == "__init__.py" or arq.stem.endswith("_fr"):
            continue
        texto = _relativo(arq.read_text(encoding="utf-8"))
        if "generated by the Catala compiler" in texto:
            texto = CABECALHO + texto
        (tmp / arq.name).write_text(texto, encoding="utf-8")
        copiados.append(arq.name)
    (tmp / "__init__.py").write_text(
        '"""Regras em Catala compiladas para Python (gerado; veja raiz/regras/catala_gerar.py)."""\n', encoding="utf-8"
    )
    info = {"catala": versao, "alvo": ALVO, "arquivos": copiados, "fontes": fontes()}
    (tmp / "ORIGEM.json").write_text(json.dumps(info, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    shutil.rmtree(PASTA_GERADO, ignore_errors=True)
    tmp.rename(PASTA_GERADO)
    return info
